package com.loonybot.sidekick;

/**
 * A 2D point using doubles, for Sidekick's Canvas functionality.
 */
public class PointD {
    public double x;
    public double y;

    public PointD(double x, double y) {
        this.x = x;
        this.y = y;
    }
}